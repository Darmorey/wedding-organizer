function cat(name: keyof typeof CATEGORY_ICONS, tasks: string[]): CategoryTemplate {
  return { name, icon: CATEGORY_ICONS[name], tasks }
}

function clonePlan(plan: CategoryTemplate[]): CategoryTemplate[] {
  return plan.map((item) => ({ ...item, tasks: [...item.tasks] }))
}

function findCategory(plan: CategoryTemplate[], name: string) {
  return plan.find((item) => item.name === name)
}

function addTasks(plan: CategoryTemplate[], name: string, tasks: string[]) {
  const category = findCategory(plan, name)
  if (!category) return
  for (const task of tasks) {
    if (!category.tasks.includes(task)) category.tasks.push(task)
  }
}

function moveCategory(plan: CategoryTemplate[], name: string, index: number) {
  const current = plan.findIndex((item) => item.name === name)
  if (current < 0) return plan
  const [item] = plan.splice(current, 1)
  plan.splice(Math.min(index, plan.length), 0, item)
  return plan
}

