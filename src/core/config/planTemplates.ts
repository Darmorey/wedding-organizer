const SIZE_PLANS = {
  small: SMALL,
  medium: MEDIUM,
  large: LARGE,
} as const

export function resolveWeddingPlan(answers: ProjectSurveyAnswers): WeddingPlan {
  return {
    ...describeWeddingPlan(answers),
    categories: buildWeddingPlan(answers),
  }
}

export function buildWeddingPlan(answers: ProjectSurveyAnswers): CategoryTemplate[] {
  const plan = clonePlan(SIZE_PLANS[answers.guests])

  if (answers.format === 'outdoor') {
    addTasks(plan, 'Площадка', [
      'Проверить план Б: крыша, шатёр, перенос при плохой погоде',
      'Уточнить электричество, туалеты и покрытие для каблуков',
      'Подготовить схему «как доехать» и парковку',
    ])
    addTasks(plan, 'День свадьбы', [
      'За 2–3 дня проверить прогноз и момент перехода на план Б',
    ])
    addTasks(plan, 'Одежда', ['Подобрать обувь и образ под траву, ветер и грунт'])
  }

  if (answers.format === 'party') {
    addTasks(plan, 'Музыка', ['Сделать акцент на плейлист и танцы, без обязательных традиций'])
    addTasks(plan, 'Кейтеринг', ['Выбрать лёгкую подачу: фуршет, станции или поздний ужин'])
  }

  if (answers.format === 'ceremony_dinner') {
    addTasks(plan, 'Документы', ['Развести по времени регистрацию и ужин, если это разные локации'])
    addTasks(plan, 'Музыка', ['Решить, нужен ли ведущий — для ужина часто достаточно плейлиста'])
  }

  if (answers.format === 'intimate_dinner') {
    addTasks(plan, 'Площадка', ['Смотреть на камерные залы, отдельный кабинет или дом'])
  }

  if (answers.format === 'banquet') {
    addTasks(plan, 'Музыка', ['Согласовать вход, поздравления, первый танец и торт с ведущим'])
  }

  if (answers.budget === 'modest') {
    addTasks(plan, 'Дата и бюджет', ['Отметить, что можно урезать: декор, полиграфия, видео, ведущий'])
    addTasks(plan, 'Фото и видео', ['При экономии выбрать фото в приоритете, видео — по остатку'])
    addTasks(plan, 'Приглашения', ['Сделать электронные приглашения, без дорогого тиража'])
    addTasks(plan, 'Декор и цветы', ['Ограничиться ключевыми зонами, не оформлять всё пространство'])
  }

  applyPriority(plan, answers.priorities)

  if (answers.organizer === 'couple') {
    addTasks(plan, 'День свадьбы', [
      'Назначить координатора дня (друг или родственник) — не держать контроль на паре',
    ])
  }
  if (answers.organizer === 'family') {
    addTasks(plan, 'Гости', ['Распределить сбор RSVP и логистику между семьями'])
    addTasks(plan, 'День свадьбы', ['Назначить ответственных: встреча гостей, подрядчики, реквизит'])
  }
  if (answers.organizer === 'day_coordinator') {
    addTasks(plan, 'День свадьбы', ['Найти координатора на день и передать ему файл дня'])
  }
  if (answers.organizer === 'planner') {
    addTasks(plan, 'Дата и бюджет', ['Собрать бриф: формат, гости, бюджет, приоритеты'])
    addTasks(plan, 'День свадьбы', ['Согласовать с организатором тайминг, контакты и остаток оплат'])
  }

  if (answers.timeline === 'six') {
    addTasks(plan, 'Дата и бюджет', ['Первый месяц параллельно: бюджет, гости, дата, площадка'])
  }
  if (answers.timeline === 'three' || answers.timeline === 'soon') {
    addTasks(plan, 'Дата и бюджет', ['Закрыть дату, бюджет и площадку в первую неделю'])
    addTasks(plan, 'Площадка', ['Брать доступные варианты, без долгого кастома'])
    addTasks(plan, 'Декор и цветы', ['Отказаться от позиций с долгим изготовлением на заказ'])
  }
  if (answers.timeline === 'season') {
    addTasks(plan, 'Дата и бюджет', ['Выбрать сезон и 2–3 резервные даты до брони площадки'])
  }

  if (answers.priorities.includes('honeymoon')) {
    moveCategory(plan, 'Медовый месяц', 1)
    addTasks(plan, 'Медовый месяц', ['Зафиксировать сумму поездки отдельно и не тратить её на свадьбу'])
  }

  return plan
}

function applyPriority(plan: CategoryTemplate[], priorities: WeddingPriority[]) {
  if (priorities.includes('venue')) {
    addTasks(plan, 'Площадка', ['Не экономить на виде и договоре площадки — это приоритет'])
  }
  if (priorities.includes('photo')) {
    addTasks(plan, 'Фото и видео', ['Забронировать фотографа сразу после даты — это приоритет'])
  }
  if (priorities.includes('party')) {
    addTasks(plan, 'Кейтеринг', ['Заложить комфорт гостей: еда, напитки, программа'])
    addTasks(plan, 'Музыка', ['Не урезать программу вечера, если гости — приоритет'])
  }
  if (priorities.includes('looks')) {
    addTasks(plan, 'Одежда', ['Заложить примерки, стилиста и аксессуары как приоритет'])
  }
}
