const TITLE_TO_PHASE = (() => {
  const map = new Map<string, DeadlinePhase>()
  for (const phase of DEADLINE_PHASES) {
    for (const title of TITLES_BY_PHASE[phase.id]) {
      map.set(normalizeTaskTitle(title), phase.id)
    }
  }
  return map
})()

export function normalizeTaskTitle(title: string) {
  return title.trim().toLowerCase().replace(/\s+/g, ' ')
}

export function isDeadlinePhase(value: unknown): value is DeadlinePhase {
  return DEADLINE_PHASES.some((phase) => phase.id === value)
}

export function deadlinePhaseOf(
  task: { title: string; metadata?: Record<string, unknown> },
  categoryName?: string,
): DeadlinePhase | null {
  const stored = task.metadata?.deadlinePhase
  if (isDeadlinePhase(stored)) return stored
  return deadlinePhaseForTitle(task.title, categoryName)
}

export function deadlinePhaseForTitle(title: string, categoryName?: string): DeadlinePhase | null {
  const fromTitle = TITLE_TO_PHASE.get(normalizeTaskTitle(title))
  if (fromTitle) return fromTitle
  if (categoryName && CATEGORY_DEFAULT[categoryName]) return CATEGORY_DEFAULT[categoryName]
  return null
}

export function deadlinePhaseLabel(phase: DeadlinePhase) {
  return DEADLINE_PHASES.find((item) => item.id === phase)?.label ?? phase
}

export function defaultDeadlineForCategory(categoryName: string): DeadlinePhase {
  return CATEGORY_DEFAULT[categoryName] ?? 'm12_9'
}
